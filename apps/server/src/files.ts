import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { S3Client, type S3Settings } from "./s3.js";

/**
 * Where attached files are kept: the data folder (`/data/uploads`, the default) or an S3-compatible bucket. Files are
 * named by the attachment's id and never change once written. This is the only place that knows where they are.
 */
export interface FileStore {
  readonly kind: "folder" | "s3";
  /** A path in the data folder to write a file to before `putFile` (removed by it). */
  tempPath(): string;
  /** Moves a file written at `tempPath()` into the store under `id`; returns its size. */
  putFile(id: string, file: string, contentType?: string): Promise<number>;
  putBuffer(id: string, data: Buffer, contentType?: string): Promise<void>;
  /** The file, or part of it (`range` inclusive), with its whole size; null when it's missing. */
  open(id: string, range?: { start: number; end: number }): Promise<{ stream: Readable; size: number } | null>;
  /** The file's size; null when it's missing. */
  size(id: string): Promise<number | null>;
  read(id: string): Promise<Buffer | null>;
  /** Copies a file under a new id; false when the source is missing. */
  copy(from: string, to: string): Promise<boolean>;
  remove(id: string): Promise<void>;
  /** Every file in the store, with when it was written. */
  list(): AsyncIterable<{ id: string; modified: Date }>;
  /** Runs `fn` with the file on the disk (copied there for a while from a bucket); null when it's missing. */
  withLocalFile<T>(id: string, fn: (file: string) => Promise<T>): Promise<T | null>;
  /** A short-lived link straight to the bucket, when the administrator allows it (FILES_S3_REDIRECT). */
  signedUrl(id: string, opts: { filename: string; contentType: string; inline: boolean }): string | null;
  /** Checks that the store can be reached (at start-up). */
  check(): Promise<void>;
  /** For people: "the data folder" or "the bucket nootion-files at s3.example.com". */
  describe(): string;
}

// Files being written, or held until their attachment row is added: the orphan cleaner leaves them alone.
const busy = new Map<string, number>();
const hold = (ids: string[]) => ids.forEach((id) => busy.set(id, (busy.get(id) ?? 0) + 1));
const release = (ids: string[]) =>
  ids.forEach((id) => {
    const n = (busy.get(id) ?? 1) - 1;
    if (n > 0) busy.set(id, n);
    else busy.delete(id);
  });
export const isFileBusy = (id: string) => busy.has(id);

/** Keeps files from the orphan cleaner until the returned function is called. */
export function keepFiles(ids: string[]): () => void {
  hold(ids);
  let done = false;
  return () => {
    if (!done) release(ids);
    done = true;
  };
}

/** Keeps files from the orphan cleaner while `fn` runs: for files written some time before their rows are added. */
export async function holdFiles<T>(ids: string[], fn: () => Promise<T>): Promise<T> {
  hold(ids);
  try {
    return await fn();
  } finally {
    release(ids);
  }
}

/** Wraps the writing calls of a store so that the cleaner never takes a file being written. */
function guarded(store: FileStore): FileStore {
  const putFile = store.putFile.bind(store);
  const putBuffer = store.putBuffer.bind(store);
  const copy = store.copy.bind(store);
  store.putFile = (id, file, type) => holdFiles([id], () => putFile(id, file, type));
  store.putBuffer = (id, data, type) => holdFiles([id], () => putBuffer(id, data, type));
  store.copy = (from, to) => holdFiles([to], () => copy(from, to));
  return store;
}

export function uploadsDir(dataDir: string): string {
  return path.join(dataDir, "uploads");
}

// Ids are UUIDs generated by the server, never a user-supplied path: no dot, no slash. Anything else in the store
// (".part" files being written, the ".incoming" folder) is ignored.
const FILE_ID = /^[A-Za-z0-9-]{1,64}$/;
export const isFileId = (id: string) => FILE_ID.test(id);

function safeId(id: string) {
  if (!isFileId(id)) throw new Error(`Not a file id: ${id}`);
  return id;
}

export class FolderStore implements FileStore {
  readonly kind = "folder" as const;
  constructor(readonly dir: string) {}

  path(id: string) {
    return path.join(this.dir, safeId(id));
  }
  tempPath() {
    fs.mkdirSync(this.dir, { recursive: true });
    return path.join(this.dir, `${randomUUID()}.part`);
  }
  async putFile(id: string, file: string) {
    const dest = this.path(id);
    try {
      await fs.promises.rename(file, dest);
    } catch (err) {
      // Another disk (a temporary folder elsewhere): copy instead.
      if ((err as NodeJS.ErrnoException).code !== "EXDEV") throw err;
      await fs.promises.copyFile(file, dest);
      await fs.promises.rm(file, { force: true });
    }
    return (await fs.promises.stat(dest)).size;
  }
  async putBuffer(id: string, data: Buffer) {
    const tmp = this.tempPath();
    try {
      await fs.promises.writeFile(tmp, data);
      await fs.promises.rename(tmp, this.path(id));
    } finally {
      await fs.promises.rm(tmp, { force: true });
    }
  }
  async open(id: string, range?: { start: number; end: number }) {
    const size = await this.size(id);
    if (size === null) return null;
    return { stream: fs.createReadStream(this.path(id), range), size };
  }
  async size(id: string) {
    try {
      const s = await fs.promises.stat(this.path(id));
      return s.isFile() ? s.size : null;
    } catch {
      return null;
    }
  }
  async read(id: string) {
    try {
      return await fs.promises.readFile(this.path(id));
    } catch {
      return null;
    }
  }
  async copy(from: string, to: string) {
    try {
      await fs.promises.mkdir(this.dir, { recursive: true });
      await fs.promises.copyFile(this.path(from), this.path(to));
      return true;
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === "ENOENT") return false;
      throw err;
    }
  }
  async remove(id: string) {
    await fs.promises.rm(this.path(id), { force: true });
  }
  async *list() {
    let names: string[];
    try {
      names = await fs.promises.readdir(this.dir);
    } catch {
      return;
    }
    for (const name of names) {
      if (!isFileId(name)) continue;
      try {
        const s = await fs.promises.stat(path.join(this.dir, name));
        if (s.isFile()) yield { id: name, modified: s.mtime };
      } catch {
        // Removed meanwhile.
      }
    }
  }
  async withLocalFile<T>(id: string, fn: (file: string) => Promise<T>) {
    if ((await this.size(id)) === null) return null;
    return fn(this.path(id));
  }
  signedUrl() {
    return null;
  }
  async check() {
    await fs.promises.mkdir(this.dir, { recursive: true });
  }
  describe() {
    return this.dir;
  }
}

export class S3Store implements FileStore {
  readonly kind = "s3" as const;
  readonly client: S3Client;
  constructor(
    settings: S3Settings,
    /** Where files wait on the disk before going to the bucket. */
    private readonly tempDir: string,
  ) {
    this.client = new S3Client(settings);
  }

  tempPath() {
    fs.mkdirSync(this.tempDir, { recursive: true });
    return path.join(this.tempDir, `${randomUUID()}.part`);
  }
  async putFile(id: string, file: string, contentType?: string) {
    try {
      const size = (await fs.promises.stat(file)).size;
      await this.client.put(safeId(id), { file, size }, contentType);
      return size;
    } finally {
      await fs.promises.rm(file, { force: true });
    }
  }
  async putBuffer(id: string, data: Buffer, contentType?: string) {
    await this.client.put(safeId(id), data, contentType);
  }
  async open(id: string, range?: { start: number; end: number }) {
    const res = await this.client.get(safeId(id), range);
    if (!res || !res.body) return null;
    // "bytes 0-99/1234" for a part, Content-Length for the whole file.
    const total = /\/(\d+)$/.exec(res.headers.get("content-range") ?? "")?.[1] ?? res.headers.get("content-length");
    return { stream: Readable.fromWeb(res.body as never), size: Number(total ?? 0) };
  }
  size(id: string) {
    return this.client.head(safeId(id));
  }
  async read(id: string) {
    const res = await this.client.get(safeId(id));
    return res ? Buffer.from(await res.arrayBuffer()) : null;
  }
  copy(from: string, to: string) {
    return this.client.copy(safeId(from), safeId(to));
  }
  remove(id: string) {
    return this.client.delete(safeId(id));
  }
  async *list() {
    for await (const o of this.client.list()) if (isFileId(o.key)) yield { id: o.key, modified: o.modified };
  }
  async withLocalFile<T>(id: string, fn: (file: string) => Promise<T>) {
    const opened = await this.open(id);
    if (!opened) return null;
    const dir = await fs.promises.mkdtemp(path.join(os.tmpdir(), "nootion-file-"));
    const file = path.join(dir, safeId(id));
    try {
      await pipeline(opened.stream, fs.createWriteStream(file));
      return await fn(file);
    } finally {
      await fs.promises.rm(dir, { recursive: true, force: true });
    }
  }
  signedUrl(id: string, opts: { filename: string; contentType: string; inline: boolean }) {
    if (!this.client.settings.redirect) return null;
    return this.client.signedUrl(safeId(id), 300, {
      "response-content-type": opts.contentType,
      "response-content-disposition": `${opts.inline ? "inline" : "attachment"}; filename*=UTF-8''${encodeURIComponent(opts.filename)}`,
    });
  }
  check() {
    return this.client.check();
  }
  describe() {
    const s = this.client.settings;
    return `s3://${s.bucket}/${s.prefix} (${new URL(s.endpoint).host})`;
  }
}

// One store per data folder: the server has one, tests make many apps side by side.
const stores = new Map<string, FileStore>();

/** Keeps a data folder's files in a bucket from now on (null: back to the folder). Called at start-up. */
export function configureFileStore(dataDir: string, s3: S3Settings | null): FileStore {
  const store = guarded(s3 ? new S3Store(s3, path.join(uploadsDir(dataDir), ".incoming")) : new FolderStore(uploadsDir(dataDir)));
  stores.set(path.resolve(dataDir), store);
  return store;
}

/** The store of a data folder: the folder itself unless `configureFileStore` gave it a bucket. */
export function fileStore(dataDir: string): FileStore {
  const key = path.resolve(dataDir);
  let store = stores.get(key);
  if (!store) {
    store = guarded(new FolderStore(uploadsDir(dataDir)));
    stores.set(key, store);
  }
  return store;
}

/** Writes a stream to a temporary file, refusing more than `maxBytes`; returns the path and the size. */
export async function streamToTemp(store: FileStore, source: Readable, maxBytes: number, tooLarge: () => Error): Promise<{ file: string; size: number }> {
  const file = store.tempPath();
  let size = 0;
  try {
    await pipeline(
      source,
      async function* (chunks: AsyncIterable<Buffer>) {
        for await (const chunk of chunks) {
          size += chunk.length;
          if (size > maxBytes) throw tooLarge();
          yield chunk;
        }
      },
      fs.createWriteStream(file),
    );
  } catch (err) {
    await fs.promises.rm(file, { force: true });
    throw err;
  }
  return { file, size };
}

export interface MoveReport {
  copied: number;
  /** Already in the destination, with the same size. */
  skipped: number;
  /** Removed from the source once copied (`removeSource`). */
  removed: number;
  failed: { id: string; error: string }[];
}

/**
 * Copies every file of one store into another (the data folder to a bucket, or back). Files already there with the same
 * size are skipped, so it can be run again after an interruption, or once more after switching, for the files added
 * meanwhile. With `removeSource`, each file leaves the source once its copy is checked.
 */
export async function moveFiles(
  from: FileStore,
  to: FileStore,
  opts: { removeSource?: boolean; concurrency?: number; onProgress?: (done: number, id: string) => void } = {},
): Promise<MoveReport> {
  const report: MoveReport = { copied: 0, skipped: 0, removed: 0, failed: [] };
  const ids: string[] = [];
  for await (const f of from.list()) ids.push(f.id);
  let next = 0;
  let done = 0;
  const worker = async () => {
    while (next < ids.length) {
      const id = ids[next++]!;
      try {
        const size = await from.size(id);
        if (size === null) continue; // removed meanwhile
        if ((await to.size(id)) === size) report.skipped++;
        else {
          const opened = await from.open(id);
          if (!opened) continue;
          const tmp = to.tempPath();
          await pipeline(opened.stream, fs.createWriteStream(tmp));
          await to.putFile(id, tmp);
          if ((await to.size(id)) !== size) throw new Error("the copy doesn't have the size of the file");
          report.copied++;
        }
        if (opts.removeSource) {
          await from.remove(id);
          report.removed++;
        }
      } catch (err) {
        report.failed.push({ id, error: (err as Error).message });
      }
      opts.onProgress?.(++done, id);
    }
  };
  await Promise.all(Array.from({ length: Math.max(1, opts.concurrency ?? 4) }, worker));
  return report;
}
